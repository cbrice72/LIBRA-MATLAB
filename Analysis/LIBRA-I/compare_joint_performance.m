function compare_joint_performance()
    %% @brief Batch processes joint accuracy and stability using data from
    %         multiple directories. This was developed specifically for
    %         comparing pre- and post-variable-gains implementation, so there
    %         are two separate data structures.

    close all; clc;

    %%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%
    % @file   compare_joint_performance.m
    % @brief  Takes two sets of log file directories, collects all the relevant
    %         data from each log file, and generates up to four different
    %         graphical analyses using per-joint position and torque metrics.
    % 
    %         Accepts any type of log file associated with the LIBRA project,
    %         whether generated by the LIBRA App (old-style CSV, newer rosbag2)
    %         or the HEBI Scope app (MAT, converted from hebilog using Scope).
    %
    % @author brice.c.aa
    % @date   2026/6/12
    %%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%

    % Script settings
    make_txt_files     = false;       % whether to save the printed details and summary to file
    make_figures       = true;        % whether to generate visualizations (total: 8)
    publication_style  = 'springer';  % the journal standard to follow for figures
    print_full_width   = false;       % whether to save half- or full-page-width figures

    % Plot style settings
    style.TITLE_WEIGHT       = 'bold';
    style.LABEL_WEIGHT       = 'normal';

    style.TEXT_COLOR         = 'k';  % black
    style.BG_COLOR           = 'w';  % white
    style.GRID_COLOR         = [0.75 0.75 0.75];  % light gray
    style.COLOR_BEFORE       = [0.29, 0.29, 0.29];  % dark gray
    style.COLOR_AFTER        = [0.85, 0.37, 0.01];  % orange

    style.BOX_SPACING        = 1.0;   % boxplots: space between groups of boxes
    style.Y_LIMIT_PERCENTILE = 98.0;  % boxplots: fallback limit for max graph height

    style.CDF_PERCENTILE     = 90.0;  % cdfs: where to draw the horizontal limit
    style.SHOW_CDF_LABELS    = true;  % cdfs: whether to show per-subgraph values

    style.BAR_WIDTH          = 0.95;  % torque jitter: space between groups of boxes

    if strcmpi(publication_style, 'springer')
        % https://link.springer.com/journal/40648/submission-guidelines#cms-Preparing-illustrations-and-figures
        style.FIG_UNITS        = 'centimeters';
        style.FULL_PAGE_WIDTH  = 17.0;  % combined eCDFs figure is always full-width
        if print_full_width
            style.FIG_WIDTH    = style.FULL_PAGE_WIDTH;
        else
            style.FIG_WIDTH    = 8.5;
        end
        style.FIG_HEIGHT       = style.FIG_WIDTH * 0.62;  % arbitrary
        
        style.PNG_RESOLUTION   = 300;  % dpi
    
        style.SHOW_TITLES      = false;
        style.FONT_SIZE_TITLE  = 10;  % pt
        style.FONT_SIZE_AXIS   = 8.5;
        style.FONT_SIZE_LEGEND = 7.5;
    
        style.LINE_WIDTH       = 1.0;  % must be > 0.25
    else
        style.LABEL_WEIGHT     = style.TITLE_WEIGHT;  % improve visibility

        style.FIG_UNITS        = 'auto';
        style.FIG_WIDTH        = 1200;
        style.FIG_HEIGHT       = style.FIG_WIDTH * 0.62;  % arbitrary

        style.PNG_RESOLUTION   = 300;
        
        style.SHOW_TITLES      = true;
        style.FONT_SIZE_TITLE  = 22;
        style.FONT_SIZE_AXIS   = 18;
        style.FONT_SIZE_LEGEND = 16;
        
        style.LINE_WIDTH       = 2.8;
    end

    % Global convenience variables
    global DEG_SYM PADDING;

    DEG_SYM = char(176);  % cross-platform degree symbol
    PADDING = '   ';      % 3 blank spaces between columns

    % Resolve pathing to shared utility scripts folder
    script_dir = fileparts(mfilename('fullpath'));
    misc_path = fullfile(script_dir, '..', '..', 'misc');  % helper scripts

    if exist(misc_path, 'dir')
        addpath(misc_path);
    end

    % List all the directories we will search for log files in
    % (NOTE: Paths can be absolute or relative to this script)
    before_dirs = { ...
        'E:\LIBRA Archive\LIBRA-I\2022-07-05 Goto-san Log Data',  ...
        'E:\LIBRA Archive\LIBRA-I\2023-11-13 Full Motion Test (bladder failure)\log',  ...
        'E:\LIBRA Archive\LIBRA-I\2023-11-14 Full Motion Test (arm failure)\log',  ...
        'E:\LIBRA Archive\LIBRA-I\2024-03-12 Takahashi Collab (ultrasonic sensor)\log',  ...
        'E:\LIBRA Archive\LIBRA-I\2024-06-24 Counterweight Measurements (18L)\log',  ...
        'E:\LIBRA Archive\LIBRA-I\2024-11-25 Upgrade Test 1\log',  ...
        'E:\LIBRA Archive\LIBRA-I\2024-11-28 Upgrade Test 2\log',  ...
        'E:\LIBRA Archive\LIBRA-I\2025-04-17 Test after J1 Replacement\log',  ...
        'E:\LIBRA Archive\LIBRA-I\2025-08-14 PID Gains Comparison\log',  ...
        'E:\LIBRA Archive\LIBRA-I\2025-08-22 SLAM Attempt 3 (motion failure)\log',  ...
        'E:\LIBRA Archive\LIBRA-I\2025-08-29 SLAM Attempt 4 (odom failure)\log' ...
    };

    after_dirs = { ...  % NOTE: "Slam Data Collection 1" does not have target data
        'E:\LIBRA Archive\LIBRA-I\2026-06-08 SLAM Data Collection 2\log' ...
    };

    %% SETUP

    joints = {'J1', 'J2', 'J3', 'J4', 'J5'};  % mechanical convention

    % Prompt user for output directory
    global OUT_DIR;  % ensure same output directory everywhere in this script

    last_dir = getpref('JointPerformanceApp', 'LastDir', script_dir);
    OUT_DIR = uigetdir(last_dir, 'Select output folder');
    if isequal(OUT_DIR, 0)
        return;  % user canceled selection
    end
    setpref('JointPerformanceApp', 'LastDir', OUT_DIR);  % remember for next run

    % Prepare output log filepaths and clear previous logs, if any
    log_basename = 'joint_performance';

    if make_txt_files
        details_file = fullfile(OUT_DIR, [log_basename, '_details.txt']);
        if exist(details_file, 'file')
            delete(details_file);
        end
    
        summary_file = fullfile(OUT_DIR, [log_basename, '_summary.txt']);
        if exist(summary_file, 'file')
            delete(summary_file);
        end
    end

    %% BODY

    % Initialize master data structs
    before = struct('position_error', [], 'torque_jitter', []);
    after  = struct('position_error', [], 'torque_jitter', []);

    % Process log files
    [before, before_count] = process_dirs(before_dirs, script_dir, before);
    [after, after_count] = process_dirs(after_dirs, script_dir, after);

    % Check parsed data
    fprintf('\nFound %d "Before" files and %d "After" files\n', before_count, after_count);
    
    if isempty(before.position_error) || isempty(after.position_error)
        error('Data aggregation failed; verify directory paths and file naming conventions');
    end

    % Analyze and plot data
    fprintf('Calculating detailed metrics...\n');

    if make_txt_files
        diary(details_file);
    end

    [box_stats, b_err, a_err] = calc_absolute_error(joints, before, after);
    [cdf_stats, b_errs_cdf, a_errs_cdf, b_ys, a_ys] = calc_error_cdfs(joints, before, after, style.CDF_PERCENTILE);
    [b_rmse, a_rmse]          = calc_rmse_radar(joints, before, after);
    [b_jitter, a_jitter]      = calc_torque_jitter(joints, before, after);

    if make_txt_files
        diary off;  % [log_basename]_details.txt
    end

    if make_figures
        fprintf('\nGenerating visualizations...\n');
        plot_absolute_error_boxplots(joints, b_err, a_err, style);
        plot_error_cdfs(joints, b_errs_cdf, a_errs_cdf, b_ys, a_ys, cdf_stats, style);
        plot_rmse_radar(joints, b_rmse, a_rmse, style);
        plot_torque_jitter(joints, b_jitter, a_jitter, style);
    end

    % Print summary
    fprintf('\nPrinting summary...\n');

    if make_txt_files
        diary(summary_file);
    end

    w_sum = 49;  % total width of summary line
    print_section_banner('JOINT PERFORMANCE SUMMARY', w_sum);
    
    h1 = 'Dataset';
    h2 = 'Total Files';
    h3 = 'Total Samples';
    print_summary_row(h1, length(h1), h2, length(h2), h3, length(h3), w_sum);
    print_rule('-', w_sum);
    print_summary_row('Before', length(h1), ...
                      num2str(before_count), length(h2), ...
                      num2str(size(before.position_error, 1)), length(h3), ...
                      w_sum);
